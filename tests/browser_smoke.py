"""Check the built demo in installed Chrome; accepts a URL and screenshot directory."""
from playwright.sync_api import sync_playwright, expect
import json, sys, re
from pathlib import Path
base = sys.argv[1].rstrip('/') + '/'
shots = Path(sys.argv[2])
shots.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, channel='chrome')
    ctx = browser.new_context(viewport={'width': 1440, 'height': 1120}, color_scheme='light')
    page = ctx.new_page()
    errors = []
    warnings = []
    page.on('pageerror', lambda e: errors.append(e.stack))
    page.on('console', lambda m: warnings.append(page.url + ' ' + m.text) if m.type in ['warning', 'error'] else None)
    page.goto(base)
    page.wait_for_load_state('networkidle')
    expect(page.locator('body')).to_have_css('opacity', '1')
    expect(page.get_by_role('heading', name='边境手记', exact=True)).to_be_visible()
    expect(page.locator('.ark-post-row')).to_have_count(4)
    expect(page.get_by_text('尚未完成的观察', exact=True)).to_have_count(0)
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
    page.screenshot(path=str(shots / 'home-light.png'))
    page.get_by_role('button', name='技术', exact=True).click()
    expect(page.locator('.ark-post-row')).to_have_count(2)
    page.get_by_role('searchbox', name='搜索文章标题').fill('小工具')
    expect(page.locator('.ark-post-row')).to_have_count(1)
    page.get_by_role('searchbox', name='搜索文章标题').fill('no-match-123')
    expect(page.get_by_text('没有找到匹配的记录。', exact=True)).to_be_visible()
    page.get_by_role('button', name='清除筛选', exact=True).click()
    expect(page.locator('.ark-post-row')).to_have_count(4)
    page.get_by_role('button', name='切换明暗模式', exact=True).click()
    expect(page.locator('html')).to_have_class(re.compile('\\bdark\\b'))
    page.screenshot(path=str(shots / 'home-dark.png'))
    page.reload()
    expect(page.locator('html')).to_have_class(re.compile('\\bdark\\b'))
    page.get_by_role('link', name='开始阅读', exact=True).click()
    expect(page.locator('.markdown-body h2')).to_have_count(5)
    expect(page.locator('.ark-toc a')).to_have_count(6)
    page.locator('.ark-toc').get_by_role('link', name='让颜色有职责', exact=True).click()
    page.wait_for_load_state('networkidle')
    expect(page).to_have_url(re.compile('%E8%AE%A9|让颜色'))
    expect(page.locator('.markdown-body table')).to_be_visible()
    assert page.locator('.markdown-body img').evaluate('(el)=>el.complete && el.naturalWidth > 0')
    page.evaluate('window.scrollTo(0, 0)')
    page.screenshot(path=str(shots / 'article-dark.png'))
    page.get_by_role('button', name='切换明暗模式', exact=True).click()
    page.screenshot(path=str(shots / 'article-light.png'))
    page.set_viewport_size({'width': 390, 'height': 844})
    page.screenshot(path=str(shots / 'article-mobile.png'), full_page=True)
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
    menu = page.get_by_role('button', name='打开导航', exact=True)
    menu.click()
    dialog = page.get_by_role('dialog', name='站点导航')
    expect(dialog).to_be_visible()
    expect(menu).to_have_attribute('aria-expanded', 'true')
    expect(dialog.get_by_role('button', name='关闭导航')).to_be_focused()
    # Wait for AK UI's staggered menu entrance before capturing its final state.
    expect(dialog.locator('[data-ak-menu-item]').last).to_have_css('opacity', '1')
    page.screenshot(path=str(shots / 'mobile-menu.png'))
    page.keyboard.press('Escape')
    expect(dialog).not_to_be_visible()
    expect(menu).to_be_focused()
    menu.click()
    dialog.get_by_role('link', name='首页', exact=True).click()
    expect(dialog).not_to_be_visible()
    page.screenshot(path=str(shots / 'home-mobile.png'), full_page=True)
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
    page.get_by_role('searchbox', name='搜索文章标题').fill('Markdown')
    expect(page.locator('.ark-post-row')).to_have_count(1)
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
    page.emulate_media(reduced_motion='reduce')
    menu.click()
    expect(dialog).to_be_visible()
    # Native modal focus must stay inside the menu.
    for _ in range(6):
        page.keyboard.press('Tab')
        assert dialog.evaluate('el=>el.contains(document.activeElement)')
    dialog.get_by_role('link', name='关于', exact=True).click()
    expect(dialog).not_to_be_visible()
    menu.click()
    page.set_viewport_size({'width':1440,'height':1120})
    expect(dialog).not_to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    expect(page.get_by_role('heading', name='关于这份手记', exact=True)).to_be_visible()
    page.goto(base + '404')
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading', name='这份记录尚未抵达。', exact=True)).to_be_visible()
    page.get_by_role('link', name='返回首页', exact=True).click()
    page.reload()
    page.wait_for_load_state('networkidle')
    page.keyboard.press('Tab')
    expect(page.get_by_role('link', name='跳至内容', exact=True)).to_be_focused()
    assert page.get_by_role('link', name='跳至内容', exact=True).bounding_box()['y'] >= 0
    page.keyboard.press('Enter')
    expect(page.locator('#ark-main')).to_be_focused()
    nojs = browser.new_context(java_script_enabled=False, viewport={'width':390,'height':844})
    static = nojs.new_page()
    static.goto(base + 'posts/reading-at-the-edge')
    expect(static.locator('.markdown-body table')).to_be_visible()
    expect(static.get_by_role('heading', name='在边界上，构建一个安静的阅读空间', exact=True)).to_be_visible()
    expect(static.get_by_role('link', name='首页', exact=True)).to_be_visible()
    expect(static.get_by_role('button', name='打开导航', exact=True)).not_to_be_visible()
    nojs.close()
    browser.close()
    assert not errors, errors
    assert not [w for w in warnings if 'hydration' in w.lower()], warnings
    print(json.dumps({'base': base, 'checks': 'SSG without JS, draft exclusion, filters, empty state, dark persistence, outline, image, mobile menu, focus trap/return, reduced motion, no-JS navigation, 404, keyboard skip', 'errors': errors, 'warnings': warnings}, ensure_ascii=False))
